# 7) الدالة الرئيسية لتشغيل الرادار
# ----------------------------------
async def main():
    session = StringSession(SESSION_STRING)
    client = TelegramClient(
        session,
        API_ID,
        API_HASH,
        connection_retries=None,
        retry_delay=5,
        auto_reconnect=True
    )

    @client.on(events.NewMessage)
    async def radar_handler(event):
        try:
            # منع التكرار
            if event.id in processed_messages:
                return
            processed_messages.add(event.id)

            msg = event.raw_text or ""
            
            # تجاهل الرسائل الفارغة
            if not msg.strip():
                return
            
            # ✅ التحقق من وجود كلمات محجوزة فقط (بدون كلمات ممنوعة)
            if not contains_only_keywords(msg):
                return

            # تجاهل الرسائل الطويلة جداً (اختياري)
            if len(msg) > 300:
                return

            print(f"🎯 تم رصد رسالة محجوزة: {msg[:50]}...")

            # استخراج تفاصيل المرسل
            sender = await event.get_sender()
            sender_id = event.sender_id
            sender_name = getattr(sender, "first_name", "") or ""
            last_name = getattr(sender, "last_name", "") or ""
            if sender_name:
                sender_name = f"{sender_name} {last_name}".strip()
            else:
                sender_name = getattr(sender, "username", None) or f"مستخدم_{sender_id}"
            
            student_mention = f"<a href='tg://user?id={sender_id}'>{html.escape(sender_name)}</a>"

            # استخراج تفاصيل المجموعة
            chat = await event.get_chat()
            group_name = getattr(chat, "title", "غير معروف")
            group_username = getattr(chat, "username", None)
            
            if group_username:
                original_message_link = f"https://t.me/{group_username}/{event.id}"
            else:
                original_message_link = f"https://t.me/c/{str(event.chat_id)[4:]}/{event.id}"
            
            group_link_display = f"@{group_username}" if group_username else "بدون معرف"

            # عدد المجموعات المشتركة
            mutual_groups = await get_common_chats_count(client, sender_id)
            current_time = datetime.now().strftime("%H:%M:%S")

            # إنشاء التقرير
            message_text = (
                f"🎯 <b>تم رصد رسالة جديدة!</b>\n\n"
                f"<b>الرسالة:</b>\n"
                f"<a href='{original_message_link}'>{html.escape(msg)}</a>\n\n"
                f"<b>الطالب:</b> {student_mention}\n"
                f"📁 <b>المجموعة:</b> {group_name} ({group_link_display})\n"
                f"📊 <b>المجموعات المشتركة:</b> {mutual_groups}\n"
                f"⏱ <b>الوقت:</b> {current_time}"
            )

            # إرسال التقرير
            await client.send_message(GROUP_ID, message_text, parse_mode="html", link_preview=False)
            print(f"✅ تم إرسال التقرير بنجاح")

        except errors.FloodWaitError as e:
            print(f"⏳ انتظار {e.seconds} ثانية...")
            await asyncio.sleep(e.seconds)
        except Exception as e:
            print(f"⚠️ خطأ في معالجة الرسالة: {e}")

    # تشغيل العميل
    await client.start()
    print("🚀 الرادار يعمل الآن - يسحب فقط الكلمات المحجوزة!")
    print(f"📋 عدد الكلمات المحجوزة: {len(KEYWORDS)}")
    print(f"🚫 عدد الكلمات الممنوعة: {len(BLACKLIST_WORDS)}")
    await client.run_until_disconnected()

