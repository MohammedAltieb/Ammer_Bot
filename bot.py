# 6) الدوال المساعدة
# ----------------------------------
async def get_common_chats_count(client, user_id):
    try:
        common = await client(functions.messages.GetCommonChatsRequest(
            user_id=user_id,
            max_id=0,
            limit=100
        ))
        return len(common.chats)
    except:
        return "غير متاح"

