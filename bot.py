# 5) دالة التحقق من الكلمات المحجوزة فقط
# ----------------------------------
def contains_only_keywords(text):
    """تتحقق إذا كانت الرسالة تحتوي على كلمات محجوزة فقط (بدون كلمات ممنوعة)"""
    text_lower = text.lower()
    
    # أولاً: تأكد من عدم وجود كلمات ممنوعة
    for banned in BLACKLIST_WORDS:
        if banned in text_lower:
            return False
    
    # ثانياً: تأكد من وجود كلمة محجوزة واحدة على الأقل
    for keyword in KEYWORDS:
        if keyword in text_lower:
            return True
    
    return False

